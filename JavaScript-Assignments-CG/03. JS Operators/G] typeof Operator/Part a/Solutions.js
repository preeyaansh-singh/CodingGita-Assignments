// JavaScript Practice – typeof Operator
// Part A


// 1. Declare name = "Rahul" and print its type.
let name = "Rahul";

console.log(typeof name); // string
// Explanation: "Rahul" is a string value.


// 2. Declare age = 25 and print its type.
let age = 25;

console.log(typeof age); // number
// Explanation: 25 is a numeric value.


// 3. Declare isStudent = true and print its type.
let isStudent = true;

console.log(typeof isStudent); // boolean
// Explanation: true is a boolean value.


// 4. Declare city without assigning a value and print its type.
let city;

console.log(typeof city); // undefined
// Explanation: A declared variable without an assigned value
// has the value undefined.


// 5. Print the type of null.
console.log(typeof null); // object
// Explanation: JavaScript returns "object" for null.
// This is a historical bug in JavaScript.
// null is actually a primitive value, not an object.


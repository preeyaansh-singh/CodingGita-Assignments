// 1. Side of a cube is 5. Calculate the volume using **= 3.
let side = 5;
side **= 3;

console.log(side); // 125
// Explanation: side = 5 ** 3 = 5 * 5 * 5 = 125
// The volume of the cube is 125 cubic units.


// 2. Square the number 4 using **= 2.
let number = 4;
number **= 2;

console.log(number); // 16
// Explanation: number = 4 ** 2 = 4 * 4 = 16


// 3. Predict the output.
let base = 2;
base **= 5;

console.log(base); // 32
// Explanation: base = 2 ** 5 = 2 * 2 * 2 * 2 * 2 = 32


// 4. Predict the output.
let n = 4;
n **= 0.5;

console.log(n); // 2
// Explanation: n = 4 ** 0.5 = √4 = 2



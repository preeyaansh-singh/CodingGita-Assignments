// 1. A counter starts at 5.
// Increase it by 1 using the increment operator.
let counter = 5;
counter++;

console.log(counter); // 6
// Explanation: counter++ increases the value by 1.
// 5 + 1 = 6


// 2. A player has 3 lives.
// Reduce one life using the decrement operator.
let lives = 3;
lives--;

console.log(lives); // 2
// Explanation: lives-- decreases the value by 1.
// 3 - 1 = 2


// 3. Start with score = 10.
// Increase the score using ++ and print it.
let score = 10;
score++;

console.log(score); // 11
// Explanation: score++ means score = score + 1.


// 4. Start with items = 8.
// Decrease the items using -- and print it.
let items = 8;
items--;

console.log(items); // 7
// Explanation: items-- means items = items - 1.


// 5. Declare count = 0.
// Increment it twice and print the final value.
let count = 0;
count++;
count++;

console.log(count); // 2
// Explanation:
// Initially, count = 0.
// First increment: 0 + 1 = 1
// Second increment: 1 + 1 = 2
